#!/usr/bin/env python3
"""Generate the Chinese-pinyin seed-word input assets (dev-time tool, not shipped).

Inputs (committed, checked against the canonical bitcoin/bips hashes below):
  deps/seedsigner-mods/data/chinese_simplified.txt   BIP-39 simplified-Chinese wordlist
  deps/seedsigner-mods/data/zh_Hans_pinyin.txt       "<char> <reading>,<reading>..." per
                                                     wordlist index (pypinyin TONE3; from
                                                     chinaverse/seedsigner-chinese)
  tools/zh_pinyin/NotoSansSC-Regular-subset-src.ttf  Noto Sans SC (SIL OFL 1.1)

Outputs:
  deps/seedsigner-mods/new_files/seedsigner/helpers/zh_pinyin_data.py
      The wordlist + readings as two frozen string constants (seedsigner/resources is
      NOT frozen into the firmware, so this data must live in an importable module).
  deps/seedsigner-lvgl-screens-mods/new_files/components/seedsigner/fonts/bip39_zh_subset.inc
      bin2c of a Noto Sans SC subset holding exactly the 2048 wordlist characters, for
      the pinyin candidate list (rasterized at runtime via lv_tiny_ttf).

Usage:  python tools/zh_pinyin/gen_assets.py     (needs: fonttools)
"""
import hashlib
import io
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
DATA = os.path.join(ROOT, "deps", "seedsigner-mods", "data")
PY_OUT = os.path.join(ROOT, "deps", "seedsigner-mods", "new_files", "seedsigner", "helpers",
                      "zh_pinyin_data.py")
FONT_SRC = os.path.join(ROOT, "tools", "zh_pinyin", "NotoSansSC-Regular-subset-src.ttf")
FONT_OUT = os.path.join(ROOT, "deps", "seedsigner-lvgl-screens-mods", "new_files", "components",
                        "seedsigner", "fonts", "bip39_zh_subset.inc")

# sha256 of bitcoin/bips bip-0039/chinese_simplified.txt (also pinned at runtime).
ZH_SHA256 = "5c5942792bd8340cb8b27cd592f1015edf56a8c5b26276ee18a482428e7c5726"


def die(msg):
    sys.exit("[zh_pinyin] FATAL: " + msg)


def load_wordlist():
    raw = open(os.path.join(DATA, "chinese_simplified.txt"), "rb").read()
    if hashlib.sha256(raw).hexdigest() != ZH_SHA256:
        die("chinese_simplified.txt does not match the canonical BIP-39 hash")
    words = raw.decode("utf-8").split("\n")[:-1]
    if len(words) != 2048 or len(set(words)) != 2048 or any(len(w) != 1 for w in words):
        die("wordlist must be 2048 unique single characters")
    return words


def load_readings(words):
    lines = open(os.path.join(DATA, "zh_Hans_pinyin.txt"), encoding="utf-8").read().split("\n")
    lines = [l for l in lines if l]
    if len(lines) != 2048:
        die("pinyin file must have 2048 lines")
    valid = re.compile(r"^[a-z]+[1-4]?$")
    out = []
    for i, line in enumerate(lines):
        char, _, readings = line.partition(" ")
        if char != words[i]:
            die("pinyin line %d is for %r, wordlist has %r" % (i, char, words[i]))
        rs = [r for r in readings.split(",") if r]
        if not rs or not all(valid.match(r) for r in rs):
            die("bad readings on line %d: %r" % (i, line))
        out.append(",".join(rs))
    return out


def write_py(words, readings):
    buf = io.StringIO()
    buf.write('"""BIP-39 simplified-Chinese wordlist + pinyin readings (GENERATED, do not edit).\n\n'
              "Generated by tools/zh_pinyin/gen_assets.py in seedsigner-micropython-builder.\n"
              "WORDS[i] is the BIP-39 word at index i; PINYIN line i holds its comma-separated\n"
              "readings (toneless syllable + tone digit 1-4, no digit = neutral; u-umlaut = v).\n"
              "Integrity is re-checked at runtime by seedsigner.helpers.zh_pinyin.\n"
              '"""\n')
    buf.write("WORDS = (\n")
    for i in range(0, 2048, 32):
        buf.write('    "%s"\n' % "".join(words[i:i + 32]))
    buf.write(")\n\n")
    buf.write("PINYIN = (\n")
    for i in range(2048):
        sep = "\\n" if i < 2047 else ""
        buf.write('    "%s%s"\n' % (readings[i], sep))
    buf.write(")\n")
    os.makedirs(os.path.dirname(PY_OUT), exist_ok=True)
    with open(PY_OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(buf.getvalue())
    print("[zh_pinyin] wrote", PY_OUT)


def write_font(words):
    from fontTools import subset
    from fontTools.ttLib import TTFont

    font = TTFont(FONT_SRC)
    cmap = font.getBestCmap()
    missing = [w for w in words if ord(w) not in cmap]
    if missing:
        die("source font lacks %d wordlist glyphs: %r" % (len(missing), missing[:10]))
    opts = subset.Options()
    opts.layout_features = []
    opts.name_IDs = ["*"]          # keep copyright / license strings (OFL)
    opts.notdef_outline = True
    opts.hinting = False
    opts.desubroutinize = True
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=sorted(ord(w) for w in words))
    sub.subset(font)
    out = io.BytesIO()
    font.save(out)
    data = out.getvalue()

    lines = [
        "// GENERATED by tools/zh_pinyin/gen_assets.py (seedsigner-micropython-builder) -- do not edit.",
        "// Noto Sans SC (SIL Open Font License 1.1, see NotoSansSC-OFL.txt) subset to exactly the",
        "// 2048 characters of the BIP-39 simplified-Chinese wordlist. Rasterized at runtime via",
        "// lv_tiny_ttf for the pinyin seed-word candidate list. sha256=%s"
        % hashlib.sha256(data).hexdigest(),
        "static const uint8_t bip39_zh_subset_ttf[] = {",
    ]
    for i in range(0, len(data), 24):
        lines.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    lines.append("};")
    lines.append("static const size_t bip39_zh_subset_ttf_len = sizeof(bip39_zh_subset_ttf);")
    os.makedirs(os.path.dirname(FONT_OUT), exist_ok=True)
    with open(FONT_OUT, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("[zh_pinyin] wrote %s (%d font bytes)" % (FONT_OUT, len(data)))


BITMAP_PX = 36   # CJK size for the 480-height profile (candidate font: Inconsolata 44px, line 41)
BITMAP_NAME = "bip39_zh_%d_4bpp" % BITMAP_PX
BITMAP_OUT = os.path.join(os.path.dirname(FONT_OUT), BITMAP_NAME + ".c")


def write_bitmap_font(words, px=BITMAP_PX):
    """Pre-rendered LVGL (lv_font_fmt_txt, 4bpp) font of the 2048 wordlist characters.

    Pre-rendering removes all runtime cost: no tiny_ttf rasterization and no glyph
    cache, whose index lives in the small internal LVGL pool (see
    docs/knowledge/cjk-glyph-cache-pool-overflow.md) -- a 100+ entry candidate list
    otherwise stalls the UI and drops glyphs once that pool runs dry.
    """
    from PIL import Image, ImageDraw, ImageFont

    font = ImageFont.truetype(FONT_SRC, size=px)
    codepoints = sorted(ord(w) for w in words)
    bitmap = bytearray()
    dscs = []
    max_above = max_below = 0
    for cp in codepoints:
        ch = chr(cp)
        left, top, right, bottom = font.getbbox(ch, anchor="ls")
        w, h = max(0, right - left), max(0, bottom - top)
        adv = int(round(font.getlength(ch)))
        if w == 0 or h == 0:
            die("empty glyph for U+%04X" % cp)
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-left, -top), ch, font=font, fill=255, anchor="ls")
        px_vals = list(img.getdata())
        start = len(bitmap)
        # 4bpp, rows NOT padded (stride 0): pack the whole glyph as one nibble stream.
        for i in range(0, len(px_vals), 2):
            hi = (px_vals[i] + 8) // 17
            lo = (px_vals[i + 1] + 8) // 17 if i + 1 < len(px_vals) else 0
            bitmap.append((hi << 4) | lo)
        dscs.append((start, adv * 16, w, h, left, -bottom))
        max_above = max(max_above, h - bottom)
        max_below = max(max_below, bottom)

    rng_start = codepoints[0]
    offsets = [cp - rng_start for cp in codepoints]
    if offsets[-1] >= 0xFFFF:
        die("codepoint span too large for SPARSE_TINY")

    out = []
    out.append("// GENERATED by tools/zh_pinyin/gen_assets.py (seedsigner-micropython-builder) -- do not edit.")
    out.append("// The 2048 BIP-39 simplified-Chinese characters, %dpx, 4bpp, pre-rendered from" % px)
    out.append("// Noto Sans SC (SIL OFL 1.1, see NotoSansSC-OFL.txt). Chained as the fallback of the")
    out.append("// pinyin candidate font. Needs LV_FONT_FMT_TXT_LARGE (bitmap > 1 MB).")
    out.append('#include "lvgl.h"')
    out.append("#if LV_FONT_FMT_TXT_LARGE")
    out.append("static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {")
    for i in range(0, len(bitmap), 32):
        out.append("    " + ",".join(str(b) for b in bitmap[i:i + 32]) + ",")
    out.append("};")
    out.append("static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {")
    out.append("    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0},")
    for d in dscs:
        out.append("    {.bitmap_index = %d, .adv_w = %d, .box_w = %d, .box_h = %d, .ofs_x = %d, .ofs_y = %d}," % d)
    out.append("};")
    out.append("static const uint16_t unicode_list_0[] = {")
    for i in range(0, len(offsets), 24):
        out.append("    " + ",".join(str(o) for o in offsets[i:i + 24]) + ",")
    out.append("};")
    out.append("static const lv_font_fmt_txt_cmap_t cmaps[] = {{")
    out.append("    .range_start = %d, .range_length = %d, .glyph_id_start = 1," % (rng_start, offsets[-1] + 1))
    out.append("    .unicode_list = unicode_list_0, .glyph_id_ofs_list = NULL,")
    out.append("    .list_length = %d, .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}};" % len(offsets))
    out.append("static const lv_font_fmt_txt_dsc_t font_dsc = {")
    out.append("    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps,")
    out.append("    .kern_dsc = NULL, .kern_scale = 0, .cmap_num = 1, .bpp = 4,")
    out.append("    .kern_classes = 0, .bitmap_format = 0,")
    out.append("};")
    out.append("const lv_font_t %s = {" % BITMAP_NAME)
    out.append("    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,")
    out.append("    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,")
    out.append("    .line_height = %d, .base_line = %d," % (max_above + max_below, max_below))
    out.append("    .subpx = LV_FONT_SUBPX_NONE,")
    out.append("    .underline_position = -%d, .underline_thickness = %d," % (max(1, px // 12), max(1, px // 24)))
    out.append("    .dsc = &font_dsc, .fallback = NULL, .user_data = NULL,")
    out.append("};")
    out.append("#endif /* LV_FONT_FMT_TXT_LARGE */")
    with open(BITMAP_OUT, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("[zh_pinyin] wrote %s (%d bitmap bytes, line_height %d, base_line %d, max glyph %dx%d)"
          % (BITMAP_OUT, len(bitmap), max_above + max_below, max_below,
             max(d[2] for d in dscs), max(d[3] for d in dscs)))


def main():
    words = load_wordlist()
    readings = load_readings(words)
    write_py(words, readings)
    write_font(words)
    write_bitmap_font(words)


if __name__ == "__main__":
    main()
