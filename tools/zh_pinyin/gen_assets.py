#!/usr/bin/env python3
"""Generate the Chinese-pinyin seed-word input assets (dev-time tool, not shipped).

Inputs (committed, checked against the canonical bitcoin/bips hashes below):
  deps/seedsigner-mods/data/chinese_simplified.txt   BIP-39 simplified-Chinese wordlist
  deps/seedsigner-mods/data/zh_Hans_pinyin.txt       "<char> <reading>,<reading>..." per
                                                     wordlist index (pypinyin TONE3; from
                                                     chinaverse/seedsigner-chinese)
  tools/zh_pinyin/NotoSansSC-Regular-subset-src.ttf  Noto Sans SC (SIL OFL 1.1)

Outputs:
  deps/seedsigner-mods/new_files/seedsigner/helpers/zh_pinyin_data.py
      The wordlist + readings as two frozen string constants (seedsigner/resources is
      NOT frozen into the firmware, so this data must live in an importable module).
  deps/seedsigner-lvgl-screens-mods/new_files/components/seedsigner/fonts/bip39_zh_subset.inc
      bin2c of a Noto Sans SC subset holding exactly the 2048 wordlist characters, for
      the pinyin candidate list (rasterized at runtime via lv_tiny_ttf).

Usage:  python tools/zh_pinyin/gen_assets.py     (needs: fonttools)
"""
import hashlib
import io
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
DATA = os.path.join(ROOT, "deps", "seedsigner-mods", "data")
PY_OUT = os.path.join(ROOT, "deps", "seedsigner-mods", "new_files", "seedsigner", "helpers",
                      "zh_pinyin_data.py")
FONT_SRC = os.path.join(ROOT, "tools", "zh_pinyin", "NotoSansSC-Regular-subset-src.ttf")
FONT_OUT = os.path.join(ROOT, "deps", "seedsigner-lvgl-screens-mods", "new_files", "components",
                        "seedsigner", "fonts", "bip39_zh_subset.inc")

# sha256 of bitcoin/bips bip-0039/chinese_simplified.txt (also pinned at runtime).
ZH_SHA256 = "5c5942792bd8340cb8b27cd592f1015edf56a8c5b26276ee18a482428e7c5726"


def die(msg):
    sys.exit("[zh_pinyin] FATAL: " + msg)


def load_wordlist():
    raw = open(os.path.join(DATA, "chinese_simplified.txt"), "rb").read()
    if hashlib.sha256(raw).hexdigest() != ZH_SHA256:
        die("chinese_simplified.txt does not match the canonical BIP-39 hash")
    words = raw.decode("utf-8").split("\n")[:-1]
    if len(words) != 2048 or len(set(words)) != 2048 or any(len(w) != 1 for w in words):
        die("wordlist must be 2048 unique single characters")
    return words


def load_readings(words):
    lines = open(os.path.join(DATA, "zh_Hans_pinyin.txt"), encoding="utf-8").read().split("\n")
    lines = [l for l in lines if l]
    if len(lines) != 2048:
        die("pinyin file must have 2048 lines")
    valid = re.compile(r"^[a-z]+[1-4]?$")
    out = []
    for i, line in enumerate(lines):
        char, _, readings = line.partition(" ")
        if char != words[i]:
            die("pinyin line %d is for %r, wordlist has %r" % (i, char, words[i]))
        rs = [r for r in readings.split(",") if r]
        if not rs or not all(valid.match(r) for r in rs):
            die("bad readings on line %d: %r" % (i, line))
        out.append(",".join(rs))
    return out


def write_py(words, readings):
    buf = io.StringIO()
    buf.write('"""BIP-39 simplified-Chinese wordlist + pinyin readings (GENERATED, do not edit).\n\n'
              "Generated by tools/zh_pinyin/gen_assets.py in seedsigner-micropython-builder.\n"
              "WORDS[i] is the BIP-39 word at index i; PINYIN line i holds its comma-separated\n"
              "readings (toneless syllable + tone digit 1-4, no digit = neutral; u-umlaut = v).\n"
              "Integrity is re-checked at runtime by seedsigner.helpers.zh_pinyin.\n"
              '"""\n')
    buf.write("WORDS = (\n")
    for i in range(0, 2048, 32):
        buf.write('    "%s"\n' % "".join(words[i:i + 32]))
    buf.write(")\n\n")
    buf.write("PINYIN = (\n")
    for i in range(2048):
        sep = "\\n" if i < 2047 else ""
        buf.write('    "%s%s"\n' % (readings[i], sep))
    buf.write(")\n")
    os.makedirs(os.path.dirname(PY_OUT), exist_ok=True)
    with open(PY_OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(buf.getvalue())
    print("[zh_pinyin] wrote", PY_OUT)


def write_font(words):
    from fontTools import subset
    from fontTools.ttLib import TTFont

    font = TTFont(FONT_SRC)
    cmap = font.getBestCmap()
    missing = [w for w in words if ord(w) not in cmap]
    if missing:
        die("source font lacks %d wordlist glyphs: %r" % (len(missing), missing[:10]))
    opts = subset.Options()
    opts.layout_features = []
    opts.name_IDs = ["*"]          # keep copyright / license strings (OFL)
    opts.notdef_outline = True
    opts.hinting = False
    opts.desubroutinize = True
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=sorted(ord(w) for w in words))
    sub.subset(font)
    out = io.BytesIO()
    font.save(out)
    data = out.getvalue()

    lines = [
        "// GENERATED by tools/zh_pinyin/gen_assets.py (seedsigner-micropython-builder) -- do not edit.",
        "// Noto Sans SC (SIL Open Font License 1.1, see NotoSansSC-OFL.txt) subset to exactly the",
        "// 2048 characters of the BIP-39 simplified-Chinese wordlist. Rasterized at runtime via",
        "// lv_tiny_ttf for the pinyin seed-word candidate list. sha256=%s"
        % hashlib.sha256(data).hexdigest(),
        "static const uint8_t bip39_zh_subset_ttf[] = {",
    ]
    for i in range(0, len(data), 24):
        lines.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    lines.append("};")
    lines.append("static const size_t bip39_zh_subset_ttf_len = sizeof(bip39_zh_subset_ttf);")
    os.makedirs(os.path.dirname(FONT_OUT), exist_ok=True)
    with open(FONT_OUT, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("[zh_pinyin] wrote %s (%d font bytes)" % (FONT_OUT, len(data)))


def main():
    words = load_wordlist()
    readings = load_readings(words)
    write_py(words, readings)
    write_font(words)


if __name__ == "__main__":
    main()
